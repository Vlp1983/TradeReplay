/**
 * Universe of ~500 most actively traded US equity and ETF options tickers.
 *
 * Each entry includes:
 *   tickerCategory – 'index_etf' or 'single_name'
 *   betaProxy      – approximate beta to SPY
 *   volMultiplier  – volatility relative to VIX (SPY=1.0)
 *   sabrRho        – SABR skew parameter (negative = put skew)
 */

import type { TickerConfig } from "../types";

// Helper to build config entries concisely
function etf(
  ticker: string,
  beta: number,
  vol: number,
  rho: number
): TickerConfig {
  return {
    ticker,
    tickerCategory: "index_etf",
    betaProxy: beta,
    volMultiplier: vol,
    sabrRho: rho,
  };
}

function sn(
  ticker: string,
  beta: number,
  vol: number,
  rho: number
): TickerConfig {
  return {
    ticker,
    tickerCategory: "single_name",
    betaProxy: beta,
    volMultiplier: vol,
    sabrRho: rho,
  };
}

