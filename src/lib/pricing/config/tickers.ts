// Build lookup map for O(1) access
const TICKER_MAP = new Map<string, TickerConfig>();
for (const cfg of TICKER_LIST) {
  TICKER_MAP.set(cfg.ticker, cfg);
}

/** Default config for tickers not in the universe. */
const DEFAULT_CONFIG: TickerConfig = {
  ticker: "UNKNOWN",
  tickerCategory: "single_name",
  betaProxy: 1.0,
  volMultiplier: 1.2,
  sabrRho: -0.3,
};

/**
 * Look up config for a ticker. Returns default config if not found.
 */
export function getTickerConfig(ticker: string): TickerConfig {
  const cfg = TICKER_MAP.get(ticker.toUpperCase());
  if (cfg) return cfg;
  return { ...DEFAULT_CONFIG, ticker: ticker.toUpperCase() };
}

/**
 * Returns the top N tickers by implied options volume ranking.
 * The list is already sorted by approximate volume.
 */
export function getTopTickers(n: number): TickerConfig[] {
  return TICKER_LIST.slice(0, n);
}

/**
 * Check if a ticker is in the universe.
 */
export function isKnownTicker(ticker: string): boolean {
  return TICKER_MAP.has(ticker.toUpperCase());
}

/**
 * Get the full ticker list.
 */
export function getAllTickers(): TickerConfig[] {
  return [...TICKER_LIST];
}
